#!/usr/bin/env python3
"""Build the Aliwal Robotics news section from tools/news/articles/*.html.

Each article file starts with a JSON metadata block inside an HTML comment:

    <!--meta
    { "slug": "...", "title": "...", "short": "...", "dek": "...",
      "date": "YYYY-MM-DD", "kicker": "...", "topic": "tariffs",
      "published": "YYYY-MM-DD", "updated": "YYYY-MM-DD (optional)",
      "update_note": "optional one-line note shown at the top",
      "keydates": [["29 Oct 2026", "What happened"], ...],
      "sources": [["Publisher: title (date)", "https://..."], ...] }
    -->
    <h2>...</h2> ... article body HTML ...

Run from the repo root:  python3 tools/news/build.py
It writes news/index.html, news/<slug>/index.html, and the latest-news block
in index.html between <!-- NEWS:START --> and <!-- NEWS:END -->.
"""
import datetime as dt
import html
import json
import os
import re
import shutil
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ARTICLES_DIR = os.path.join(ROOT, "tools", "news", "articles")
NEWS_DIR = os.path.join(ROOT, "news")
HOME = os.path.join(ROOT, "index.html")
GENERATED = "<!-- generated by tools/news/build.py -->"

# Order here is the order on the news page.
TOPICS = {
    "tariffs": ("Tariffs & import rules", "Duties, exclusions and import bans that change what parts cost to land in the US."),
    "us-facilities": ("US robotics facilities", "Robot and component plants opening in the US, and what they mean for parts supply."),
}
REQUIRED = ["slug", "title", "short", "dek", "date", "kicker", "topic", "published", "keydates", "sources"]


def esc(s):
    return html.escape(str(s), quote=True)


def fmt(d):
    return dt.date.fromisoformat(d).strftime("%-d %b %Y")


def load():
    arts = []
    for name in sorted(os.listdir(ARTICLES_DIR)):
        if not name.endswith(".html"):
            continue
        text = open(os.path.join(ARTICLES_DIR, name), encoding="utf-8").read()
        m = re.match(r"\s*<!--meta\s*(\{.*?\})\s*-->\s*(.*)\Z", text, re.S)
        if not m:
            sys.exit(f"{name}: missing <!--meta {{...}} --> header")
        meta = json.loads(m.group(1))
        missing = [k for k in REQUIRED if k not in meta]
        if missing:
            sys.exit(f"{name}: missing fields {missing}")
        if meta["topic"] not in TOPICS:
            sys.exit(f"{name}: unknown topic {meta['topic']!r}; add it to TOPICS")
        if meta["slug"] + ".html" != name:
            sys.exit(f"{name}: slug must match file name")
        if not meta["sources"]:
            sys.exit(f"{name}: needs at least one source")
        for d in ("date", "published", "updated"):
            if d in meta:
                dt.date.fromisoformat(meta[d])
        meta["body"] = m.group(2).strip()
        arts.append(meta)
    arts.sort(key=lambda a: (a["date"], a["slug"]), reverse=True)
    return arts


def head(title, desc, current=""):
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>{esc(title)}</title>
<meta name="description" content="{esc(desc)}">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@62..125,400..800&family=IBM+Plex+Mono:wght@400;500&display=swap">
<link rel="stylesheet" href="/assets/site.css">
</head>
<body>
{GENERATED}
<div class="wrap">
  <header class="bar">
    <a class="mark" href="/" aria-label="Aliwal Robotics home">
      <svg viewBox="0 0 22 22" aria-hidden="true"><rect x="1" y="1" width="20" height="20" fill="none" stroke="currentColor" stroke-width="2"/><rect x="11" y="11" width="10" height="10" fill="var(--signal)"/></svg>
      <span>Aliwal Robotics</span>
    </a>
    <nav class="links" aria-label="Main">
      <a href="/news/"{current}>News</a>
      <a class="cta" href="/intake/">Request a quote</a>
    </nav>
  </header>
"""


FOOT = """
  <footer class="foot">
    <span>© 2026 Aliwal Robotics</span>
    <span><a href="/news/">News</a> · <a href="/intake/">Request a quote</a></span>
  </footer>
</div>
</body>
</html>
"""


def disclaimer(asof):
    return ("General information as of {d}, compiled from the sources listed. It is not legal, tax or customs advice. "
            "Tariff measures change often; confirm the treatment of a specific product with a licensed customs broker "
            "or the issuing agency before you rely on it.").format(d=fmt(asof))


def article_page(a):
    topic_name = TOPICS[a["topic"]][0]
    kd = "\n".join(f'          <li><time>{esc(d)}</time>{esc(t)}</li>' for d, t in a["keydates"])
    src = "\n".join(f'            <li><a href="{esc(u)}" rel="noopener" target="_blank">{esc(t)}</a></li>' for t, u in a["sources"])
    stamp = f'Published {fmt(a["published"])}'
    asof = a.get("updated", a["published"])
    if "updated" in a:
        stamp += f' · Updated {fmt(a["updated"])}'
    note = f'\n      <div class="callout"><p><strong>Update:</strong> {esc(a["update_note"])}</p></div>' if a.get("update_note") else ""
    return head(a["short"] + " · Aliwal Robotics", a["dek"]) + f"""
  <main>
    <section class="article-head">
      <p class="eyebrow"><a href="/news/" style="text-decoration:none">News</a> / <a href="/news/#{a["topic"]}" style="text-decoration:none">{esc(topic_name)}</a></p>
      <h1>{esc(a["title"])}</h1>
      <p class="dek">{esc(a["dek"])}</p>
      <p class="meta">{stamp} · Aliwal Robotics</p>{note}
    </section>

    <div class="article">
      <aside>
        <h2>Key dates</h2>
        <ul class="keydates">
{kd}
        </ul>
      </aside>
      <div class="body">
{a["body"]}
        <section class="sources">
          <h2>Sources</h2>
          <ol>
{src}
          </ol>
        </section>
        <p class="disclaimer">{esc(disclaimer(asof))}</p>
      </div>
    </div>

    <div class="next">
      <p>Need parts landed without surprises?</p>
      <a class="btn" href="/intake/">Request a quote</a>
    </div>
  </main>
""" + FOOT


def list_items(arts, indent):
    out = []
    for a in arts:
        out.append(
            f'{indent}<li><a href="/news/{a["slug"]}/"><span><time datetime="{a["date"]}">{fmt(a["date"])}</time>'
            f'<span class="k">{esc(a["kicker"])}</span></span>'
            f'<span><span class="t">{esc(a["title"])}</span><span class="d">{esc(a["dek"])}</span></span></a></li>')
    return "\n".join(out)


def index_page(arts):
    latest = max(a.get("updated", a["published"]) for a in arts)
    chips = "\n".join(
        f'      <a href="#{k}">{esc(v[0])} <span>{sum(1 for a in arts if a["topic"] == k)}</span></a>'
        for k, v in TOPICS.items())
    sections = []
    for k, (name, blurb) in TOPICS.items():
        items = [a for a in arts if a["topic"] == k]
        if not items:
            continue
        sections.append(f"""
    <section class="topic" id="{k}" aria-labelledby="{k}-h">
      <div class="section-head">
        <h2 id="{k}-h">{esc(name)}</h2>
      </div>
      <p class="topic-blurb">{esc(blurb)}</p>
      <ul class="news-list">
{list_items(items, "        ")}
      </ul>
    </section>""")
    return head("Import & Tariff News · Aliwal Robotics",
                "US tariff, import-ban and robotics-facility news for buyers of robotics components and data-collection devices.",
                ' aria-current="page"') + f"""
  <main>
    <section class="article-head">
      <p class="eyebrow">News</p>
      <h1>US import, tariff and facility news for robotics buyers</h1>
      <p class="dek">Short briefings on the tariffs, exclusions, import bans and new US plants that change what robotics components and data-collection devices cost and how fast they arrive. Updated {fmt(latest)}.</p>
    </section>
    <nav class="topic-nav" aria-label="Topics">
{chips}
    </nav>
{"".join(sections)}
    <p class="disclaimer">{esc(disclaimer(latest))}</p>
  </main>
""" + FOOT


def main():
    arts = load()
    os.makedirs(NEWS_DIR, exist_ok=True)
    keep = {a["slug"] for a in arts}
    # Remove pages for articles that no longer exist (only ones this script generated).
    for name in os.listdir(NEWS_DIR):
        p = os.path.join(NEWS_DIR, name, "index.html")
        if os.path.isdir(os.path.join(NEWS_DIR, name)) and name not in keep and os.path.exists(p) and GENERATED in open(p, encoding="utf-8").read():
            shutil.rmtree(os.path.join(NEWS_DIR, name))
    for a in arts:
        d = os.path.join(NEWS_DIR, a["slug"])
        os.makedirs(d, exist_ok=True)
        open(os.path.join(d, "index.html"), "w", encoding="utf-8").write(article_page(a))
    open(os.path.join(NEWS_DIR, "index.html"), "w", encoding="utf-8").write(index_page(arts))

    home = open(HOME, encoding="utf-8").read()
    block = "<!-- NEWS:START -->\n" + list_items(arts[:3], "        ") + "\n        <!-- NEWS:END -->"
    new_home, n = re.subn(r"<!-- NEWS:START -->.*?<!-- NEWS:END -->", block, home, flags=re.S)
    if n != 1:
        sys.exit("index.html: NEWS:START/END markers not found")
    open(HOME, "w", encoding="utf-8").write(new_home)
    print(f"Built {len(arts)} articles; home shows: {[a['slug'] for a in arts[:3]]}")


if __name__ == "__main__":
    main()
